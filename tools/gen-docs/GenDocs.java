    /** Long flags first, then short ones, each alphabetically. */
    static final java.util.Comparator<String> FLAG_ORDER = (a, c) -> {
        boolean la = a.startsWith("--"), lc = c.startsWith("--");
        if (la != lc) return la ? -1 : 1;
        return a.compareTo(c);
    };

    static final class CliCommand {
        List<String> names = new ArrayList<>();
        String usageClass;
        String flagClass;
        String desc;
    }

    /** The commands of GatfCli.main's if/else chain: the args[0] literals and the classes the branch hands over to. */
    List<CliCommand> cliCommands(Src cli) {
        List<CliCommand> out = new ArrayList<>();
        MethodTree main = cli.findMethod("GatfCli", "main");
        if (main == null) { problems.add("GatfCli.main not found"); return out; }
        new TreeScanner<Void, Void>() {
            @Override
            public Void visitIf(IfTree node, Void p) {
                List<String> names = new ArrayList<>();
                new TreeScanner<Void, Void>() {
                    @Override
                    public Void visitMethodInvocation(MethodInvocationTree mi, Void q) {
                        if (mi.getMethodSelect() instanceof MemberSelectTree) {
                            MemberSelectTree ms = (MemberSelectTree) mi.getMethodSelect();
                            if (ms.getIdentifier().contentEquals("equals") && ms.getExpression().toString().equals("args[0]")
                                    && mi.getArguments().size() == 1 && mi.getArguments().get(0) instanceof LiteralTree) {
                                names.add(String.valueOf(((LiteralTree) mi.getArguments().get(0)).getValue()));
                            }
                        }
                        return super.visitMethodInvocation(mi, q);
                    }
                }.scan(node.getCondition(), null);
                if (names.isEmpty()) return super.visitIf(node, p);   // a guard such as `args.length>=1`: look inside
                {
                    CliCommand c = new CliCommand();
                    c.names.addAll(names);
                    // the classes the branch calls; the first with a USAGE constant gives the usage, the first parser gives the flags
                    List<String> called = new ArrayList<>();
                    new TreeScanner<Void, Void>() {
                        @Override
                        public Void visitMethodInvocation(MethodInvocationTree mi, Void q) {
                            if (mi.getMethodSelect() instanceof MemberSelectTree) {
                                String recv = ((MemberSelectTree) mi.getMethodSelect()).getExpression().toString();
                                String fqn = cli.resolve(recv);
                                if (fqn != null && fqn.startsWith("com.gatf.") && sourceOf(fqn) != null && !called.contains(fqn)) called.add(fqn);
                            }
                            return super.visitMethodInvocation(mi, q);
                        }
                    }.scan(firstBlock(node.getThenStatement()), null);
                    for (String fqn : called) {
                        Src s;
                        try { s = src(sourceOf(fqn)); } catch (IOException e) { continue; }
                        if (c.usageClass == null && s.hasStaticField("USAGE")) c.usageClass = fqn;
                    }
                    c.flagClass = c.usageClass;
                    out.add(c);
                }
                // keep walking the else-if chain only
                scan(node.getElseStatement(), null);
                return null;
            }
        }.scan(main.getBody(), null);
        return out;
    }

    static Tree firstBlock(StatementTree s) {
        return s;
    }

