    static final class RouteInfo {
        String handler;
        String desc;
        boolean websocket;
        Set<String> params = new TreeSet<>();
        Map<String, Set<String>> selectors = new LinkedHashMap<>();
    }

    static final Set<String> SELECTORS = new LinkedHashSet<>(List.of("action", "sub", "pluginType", "configType"));

    RouteInfo routeInfo(Src s) {
        RouteInfo ri = new RouteInfo();
        new TreeScanner<Void, Void>() {
            @Override
            public Void visitMethodInvocation(MethodInvocationTree mi, Void p) {
                if (mi.getMethodSelect() instanceof MemberSelectTree) {
                    MemberSelectTree ms = (MemberSelectTree) mi.getMethodSelect();
                    String id = ms.getIdentifier().toString();
                    List<? extends ExpressionTree> a = mi.getArguments();
                    if (id.equals("getParameter") && a.size() == 1 && a.get(0) instanceof LiteralTree) {
                        ri.params.add(String.valueOf(((LiteralTree) a.get(0)).getValue()));
                    }
                    if ((id.equals("equals") || id.equals("equalsIgnoreCase")) && a.size() == 1) {
                        String recv = ms.getExpression().toString();
                        ExpressionTree arg = a.get(0);
                        if (SELECTORS.contains(recv) && arg instanceof LiteralTree) add(recv, ((LiteralTree) arg).getValue());
                        if (ms.getExpression() instanceof LiteralTree && SELECTORS.contains(arg.toString())) add(arg.toString(), ((LiteralTree) ms.getExpression()).getValue());
                    }
                }
                return super.visitMethodInvocation(mi, p);
            }

            @Override
            public Void visitSwitch(SwitchTree st, Void p) {
                String sel = unparen(st.getExpression()).toString();
                if (SELECTORS.contains(sel)) {
                    for (CaseTree c : st.getCases()) for (ExpressionTree e : c.getExpressions()) if (e instanceof LiteralTree) add(sel, ((LiteralTree) e).getValue());
                }
                return super.visitSwitch(st, p);
            }

            void add(String sel, Object v) {
                ri.selectors.computeIfAbsent(sel, k -> new LinkedHashSet<>()).add(String.valueOf(v));
            }
        }.scan(s.cu, null);
        return ri;
    }

    static ExpressionTree unparen(ExpressionTree e) {
        while (e instanceof ParenthesizedTree) e = ((ParenthesizedTree) e).getExpression();
        return e;
    }

