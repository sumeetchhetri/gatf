    public static void main(String[] args) throws Exception {
        Path repo = Paths.get(".");
        String cmd = "check";
        for (int i = 0; i < args.length; i++) {
            if (args[i].equals("--repo") && i + 1 < args.length) repo = Paths.get(args[++i]);
            else if (args[i].equals("generate") || args[i].equals("check")) cmd = args[i];
            else {
                System.err.println("usage: java tools/gen-docs/GenDocs.java [--repo <dir>] generate|check");
                System.exit(2);
            }
        }
        if (!Files.isDirectory(repo.resolve(MAIN))) {
            System.err.println("not a GATF checkout (no " + MAIN + "): " + repo.toAbsolutePath());
            System.exit(2);
        }
        List<String> out;
        if (cmd.equals("generate")) {
            out = generate(repo);
            System.out.println("gen-docs: wrote docs/reference (" + pages(repo).size() + " pages)");
        } else {
            out = check(repo);
        }
        for (String p : out) System.err.println("  " + p);
        if (!out.isEmpty()) {
            System.err.println("gen-docs " + cmd + ": " + out.size() + " problem(s)");
            System.exit(1);
        }
        if (cmd.equals("check")) System.out.println("gen-docs check: ok");
    }

    /** Writes docs/reference/*.md. Returns the description problems (pages are written anyway, with gaps marked). */
    public static List<String> generate(Path repo) throws IOException {
        GenDocs g = new GenDocs(repo);
        Map<String, String> pages = g.render();
        Path dir = g.repo.resolve("docs/reference");
        Files.createDirectories(dir);
        for (Map.Entry<String, String> e : pages.entrySet()) {
            Files.write(g.repo.resolve(e.getKey()), e.getValue().getBytes(StandardCharsets.UTF_8));
        }
        g.staleKeys();
        return g.problems;
    }

    /** Every problem: stale generated pages, missing/stale descriptions, broken links, missing front matter, MDX-only syntax. */
    public static List<String> check(Path repo) throws IOException {
        return check(repo, Collections.emptyMap());
    }

    /** {@link #check(Path)} with some sources replaced in memory (repo-relative path -> text). */
    public static List<String> check(Path repo, Map<String, String> sourceOverrides) throws IOException {
        GenDocs g = new GenDocs(repo);
        g.overrides.putAll(sourceOverrides);
        Map<String, String> pages = g.render();
        for (Map.Entry<String, String> e : pages.entrySet()) {
            Path p = g.repo.resolve(e.getKey());
            String disk = Files.exists(p) ? new String(Files.readAllBytes(p), StandardCharsets.UTF_8) : null;
            if (disk == null) g.problems.add(e.getKey() + ": missing; run `java tools/gen-docs/GenDocs.java generate`");
            else if (!disk.equals(e.getValue())) g.problems.add(e.getKey() + ": out of date with the sources (" + firstDiff(disk, e.getValue())
                    + "); run `java tools/gen-docs/GenDocs.java generate`");
        }
        try (Stream<Path> s = Files.list(g.repo.resolve("docs/reference"))) {
            for (Path p : s.collect(Collectors.toList())) {
                String rel = g.rel(p);
                if (rel.endsWith(".md") && !pages.containsKey(rel)) g.problems.add(rel + ": not produced by the generator (docs/reference is generated only)");
            }
        } catch (IOException ignored) {
            // reported above as missing pages
        }
        g.staleKeys();
        g.seleasyCoverage();
        g.lintMarkdown();
        return g.problems;
    }

    /** The generated pages, keyed by repo-relative path (for tests). */
    public static Map<String, String> pages(Path repo) throws IOException {
        return new GenDocs(repo).render();
    }

    /** One fenced code block in the docs. */
    public static final class Snippet {
        public final String file;
        public final int line;
        public final String lang;
        public final String meta;
        public final String code;

        Snippet(String file, int line, String lang, String meta, String code) {
            this.file = file;
            this.line = line;
            this.lang = lang;
            this.meta = meta;
            this.code = code;
        }

        @Override
        public String toString() {
            return file + ":" + line + " (" + (lang.isEmpty() ? "no language" : lang) + ")";
        }
    }

    /** Every fenced code block in README.md and docs/** (docs/deltas excluded). */
    public static List<Snippet> snippets(Path repo) throws IOException {
        GenDocs g = new GenDocs(repo);
        List<Snippet> out = new ArrayList<>();
        for (Path md : g.markdownFiles()) {
            List<String> lines = readLines(md);
            String rel = g.rel(md);
            for (Fence f : fences(lines)) {
                out.add(new Snippet(rel, f.start + 1, f.lang, f.meta, String.join("\n", lines.subList(f.start + 1, f.end)) + "\n"));
            }
        }
        return out;
    }

