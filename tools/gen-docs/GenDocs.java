    void seleasyCoverage() throws IOException {
        String ref = new String(Files.readAllBytes(repo.resolve("docs/seleasy/REFERENCE.md")), StandardCharsets.UTF_8);
        List<String> codeLines = new ArrayList<>();
        List<String> lines = Arrays.asList(ref.split("\n", -1));
        for (Fence f : fences(lines)) for (int i = f.start + 1; i < f.end; i++) codeLines.add(lines.get(i).trim());
        Set<String> spans = new HashSet<>();
        Matcher m = Pattern.compile("`([^`\n]+)`").matcher(ref);
        while (m.find()) spans.add(m.group(1).trim());
        for (Map<String, Object> c : commandsJson()) {
            String kw = String.valueOf(c.get("keyword"));
            String exempt = describe("seleasy-exempt.properties", kw.replace(" ", "_"), null);
            if (exempt != null) continue;
            boolean found = false;
            for (String l : codeLines) {
                if (l.equals(kw) || (!Character.isLetterOrDigit(kw.charAt(kw.length() - 1)) && l.startsWith(kw)) || l.startsWith(kw + " ") || l.startsWith(kw + "\t") || l.startsWith(kw + "(") || ("regex".equals(c.get("match")) && Pattern.compile("(^|\\s)" + Pattern.quote(kw) + "!?(\\s|$)").matcher(l).find())) { found = true; break; }
            }
            if (!found) for (String s : spans) if (s.equals(kw) || s.startsWith(kw + " ")) { found = true; break; }
            if (!found) problems.add("docs/seleasy/REFERENCE.md: keyword `" + kw + "` (" + c.get("class") + ") is not documented: add it to a syntax block, "
                    + "or list it in tools/gen-docs/descriptions/seleasy-exempt.properties with the reason");
        }
    }

