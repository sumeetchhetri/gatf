    void lintMarkdown() throws IOException {
        Map<String, String> positions = new HashMap<>();   // folder + position -> page, to catch two pages in one slot
        for (Path md : markdownFiles()) {
            String rel = rel(md);
            List<String> lines = readLines(md);
            boolean isNew = false;
            for (String d : NEW_DIRS) if (rel.startsWith(d + "/")) isNew = true;
            for (String f : NEW_FILES) if (rel.equals(f)) isNew = true;
            if (isNew) {
                for (String l : lines.subList(0, Math.min(lines.size(), 6))) {
                    Matcher pm = Pattern.compile("^sidebar_position: (\\d+)$").matcher(l);
                    if (!pm.find()) continue;
                    String slot = rel.substring(0, rel.lastIndexOf('/') + 1) + "#" + pm.group(1);
                    String other = positions.put(slot, rel);
                    if (other != null) problems.add(rel + ": sidebar_position " + pm.group(1) + " is also used by " + other);
                }
                frontMatterCheck(rel, lines);
                portability(rel, lines);
            }
            links(md, rel, lines);
            for (Fence f : fences(lines)) {
                if (f.lang.equals("seleasy")) problems.add(rel + ":" + (f.start + 1) + ": tag seleasy code blocks as `sel` (the docs site highlights that tag)");
            }
        }
        for (String f : NEW_FILES) if (!Files.exists(repo.resolve(f))) problems.add(f + ": missing (the docs home page)");
    }

    void frontMatterCheck(String rel, List<String> lines) {
        if (lines.isEmpty() || !lines.get(0).equals("---")) { problems.add(rel + ": no front matter (title, sidebar_position)"); return; }
        int end = lines.subList(1, lines.size()).indexOf("---");
        if (end < 0) { problems.add(rel + ": unterminated front matter"); return; }
        boolean title = false, pos = false;
        for (String l : lines.subList(1, end + 1)) {
            if (l.matches("title: \\S.*")) title = true;
            if (l.matches("sidebar_position: \\d+")) pos = true;
        }
        if (!title) problems.add(rel + ": front matter has no `title:`");
        if (!pos) problems.add(rel + ": front matter has no numeric `sidebar_position:`");
    }

    /** Plain GitHub Markdown that the docs site also renders: no JSX/HTML, no MDX expressions, no admonitions, no ESM. */
    void portability(String rel, List<String> lines) {
        for (Fence f : fences(lines)) {
            if (f.lang.isEmpty()) problems.add(rel + ":" + (f.start + 1) + ": code block without a language (use sel, xml, json, bash, text, ...)");
            if (f.end >= lines.size()) problems.add(rel + ":" + (f.start + 1) + ": unterminated code block");
        }
        boolean[] inFence = fenceMask(lines);
        for (int i = 0; i < lines.size(); i++) {
            if (inFence[i]) continue;
            String l = stripCodeSpans(lines.get(i));
            String where = rel + ":" + (i + 1) + ": ";
            if (l.contains("{") || l.contains("}")) problems.add(where + "`{` or `}` outside code (an MDX expression on the site); put it in a code span");
            if (Pattern.compile("<[A-Za-z/!]").matcher(l).find()) problems.add(where + "HTML/JSX tag, comment or autolink outside code; use Markdown or a code span");
            if (l.startsWith(":::")) problems.add(where + "admonition (`:::`) is site-only syntax");
            if (l.matches("^(import|export)\\s.*")) problems.add(where + "MDX import/export line");
        }
    }

    static String stripCodeSpans(String l) {
        return l.replaceAll("``.+?``", "").replaceAll("`[^`]*`", "");
    }

    /** Reference-style link definitions: `[label]: target`. */
    static final Pattern REF_DEF = Pattern.compile("^\\s{0,3}\\[[^\\]]+\\]:\\s*<?([^\\s>]+)>?");
    /** HTML attributes that point at files: src="…", href="…" (in any page, including the existing ones). */
    static final Pattern HTML_REF = Pattern.compile("(?i)\\b(?:src|href)\\s*=\\s*[\"']([^\"']+)[\"']");
    static final Pattern LINK = Pattern.compile("!?\\[(?:[^\\]\\[]|\\[[^\\]]*\\])*\\]\\(([^)\\s]+)(?:\\s+\"[^\"]*\")?\\)");

    void links(Path md, String rel, List<String> lines) throws IOException {
        boolean[] inFence = fenceMask(lines);
        boolean underDocs = rel.startsWith("docs/");
        for (int i = 0; i < lines.size(); i++) {
            if (inFence[i]) continue;
            String line = stripCodeSpans(lines.get(i));
            List<String> targets = new ArrayList<>();
            Matcher lm = LINK.matcher(line);
            while (lm.find()) targets.add(lm.group(1));
            Matcher dm = REF_DEF.matcher(line);
            if (dm.find()) targets.add(dm.group(1));
            Matcher hm = HTML_REF.matcher(line);
            while (hm.find()) targets.add(hm.group(1));
            for (String target : targets) {
                if (target.matches("^[a-zA-Z][a-zA-Z0-9+.-]*:.*")) continue;   // http:, https:, mailto:
                String where = rel + ":" + (i + 1) + ": link `" + target + "`";
                String file = target, anchor = null;
                int h = target.indexOf('#');
                if (h >= 0) { file = target.substring(0, h); anchor = target.substring(h + 1); }
                Path dest = file.isEmpty() ? md : md.getParent().resolve(file).normalize();
                if (!dest.startsWith(repo)) { problems.add(where + " leaves the repository"); continue; }
                if (underDocs && !dest.startsWith(repo.resolve("docs"))) {
                    problems.add(where + " leaves docs/ (the docs site cannot resolve it); link " + GITHUB_BLOB + rel(dest) + " instead");
                    continue;
                }
                if (!Files.exists(dest)) { problems.add(where + ": no such file"); continue; }
                if (underDocs && Files.isDirectory(dest)) { problems.add(where + ": a folder, not a page (the docs site cannot link it); link its index page"); continue; }
                if (anchor != null && anchor.isEmpty()) { problems.add(where + ": empty anchor"); continue; }
                if (anchor != null) {
                    if (Files.isDirectory(dest) || !dest.toString().endsWith(".md")) { problems.add(where + ": anchor on a non-Markdown target"); continue; }
                    if (!anchors(dest).contains(anchor)) problems.add(where + ": no heading `#" + anchor + "` in " + rel(dest));
                }
            }
        }
    }

    final Map<Path, Set<String>> anchorCache = new HashMap<>();

    Set<String> anchors(Path md) throws IOException {
        Set<String> c = anchorCache.get(md);
        if (c != null) return c;
        Set<String> out = new HashSet<>();
        Map<String, Integer> seen = new HashMap<>();
        List<String> lines = readLines(md);
        boolean[] inFence = fenceMask(lines);
        for (int i = 0; i < lines.size(); i++) {
            if (inFence[i]) continue;
            Matcher m = Pattern.compile("^#{1,6}\\s+(.*?)\\s*#*\\s*$").matcher(lines.get(i));
            if (!m.find()) continue;
            String s = slug(m.group(1));
            int n = seen.merge(s, 1, Integer::sum) - 1;
            out.add(n == 0 ? s : s + "-" + n);
        }
        anchorCache.put(md, out);
        return out;
    }

    /** github-slugger (also what the docs site uses): the heading's text, lower-cased, punctuation dropped, spaces to hyphens. */
    static String slug(String heading) {
        String t = heading.replaceAll("!?\\[([^\\]]*)\\]\\([^)]*\\)", "$1").replace("`", "").replace("**", "").replace("*", "");
        t = t.toLowerCase(Locale.ROOT);
        StringBuilder b = new StringBuilder();
        t.codePoints().forEach(cp -> {
            if (cp == ' ') b.append('-');
            else if (cp == '-' || cp == '_' || Character.isLetterOrDigit(cp) || Character.getType(cp) == Character.NON_SPACING_MARK) b.appendCodePoint(cp);
        });
        return b.toString();
    }

    // ------------------------------------------------------------------------------------------------ fences

    static final class Fence {
        int start, end;
        String lang = "", meta = "";
    }

    /** Fenced code blocks (``` or ~~~, any indent up to 3 spaces; a longer closing fence also closes). */
    static List<Fence> fences(List<String> lines) {
        List<Fence> out = new ArrayList<>();
        Pattern open = Pattern.compile("^( {0,3})(`{3,}|~{3,})\\s*([^`\\s]*)\\s*(.*)$");
        for (int i = 0; i < lines.size(); i++) {
            Matcher m = open.matcher(lines.get(i));
            if (!m.find()) continue;
            String fence = m.group(2);
            Fence f = new Fence();
            f.start = i;
            f.lang = m.group(3).toLowerCase(Locale.ROOT);
            f.meta = m.group(4).trim();
            int j = i + 1;
            for (; j < lines.size(); j++) {
                String t = lines.get(j).trim();
                if (t.startsWith(fence.substring(0, 3)) && t.chars().allMatch(ch -> ch == fence.charAt(0)) && t.length() >= fence.length()) break;
            }
            f.end = Math.min(j, lines.size());
            out.add(f);
            i = j;
        }
        return out;
    }

    static boolean[] fenceMask(List<String> lines) {
        boolean[] mask = new boolean[lines.size()];
        for (Fence f : fences(lines)) for (int i = f.start; i <= f.end && i < mask.length; i++) mask[i] = true;
        return mask;
    }

    // ------------------------------------------------------------------------------------------------ sources

    String rel(Path p) {
        return repo.relativize(p.toAbsolutePath().normalize()).toString().replace('\\', '/');
    }

    Path sourceOf(String fqn) {
        if (fqn == null) return null;
        Path p = repo.resolve(MAIN + fqn.replace('.', '/') + ".java");
        return Files.exists(p) ? p : null;
    }

    Src src(Path p) throws IOException {
        Src s = parsed.get(p);
        if (s == null) {
            s = new Src(p);
            parsed.put(p, s);
        }
        return s;
    }

    static String simple(String fqn) {
        return fqn.substring(fqn.lastIndexOf('.') + 1);
    }

    static String annName(AnnotationTree a) {
        String n = a.getAnnotationType().toString();
        return n.substring(n.lastIndexOf('.') + 1);
    }

    static String annArg(AnnotationTree a, String name) {
        for (ExpressionTree e : a.getArguments()) {
            if (e instanceof com.sun.source.tree.AssignmentTree) {
                com.sun.source.tree.AssignmentTree as = (com.sun.source.tree.AssignmentTree) e;
                if (as.getVariable().toString().equals(name) && as.getExpression() instanceof LiteralTree) return String.valueOf(((LiteralTree) as.getExpression()).getValue());
            } else if (name.equals("value") && e instanceof LiteralTree) {
                return String.valueOf(((LiteralTree) e).getValue());
            }
        }
        return null;
    }

    static List<String> readLines(Path p) throws IOException {
        String s = new String(Files.readAllBytes(p), StandardCharsets.UTF_8).replace("\r\n", "\n");
        List<String> l = new ArrayList<>(Arrays.asList(s.split("\n", -1)));
        if (!l.isEmpty() && l.get(l.size() - 1).isEmpty()) l.remove(l.size() - 1);
        return l;
    }

    static String firstDiff(String a, String b) {
        String[] x = a.split("\n", -1), y = b.split("\n", -1);
        for (int i = 0; i < Math.max(x.length, y.length); i++) {
            String p = i < x.length ? x[i] : "<end>", q = i < y.length ? y[i] : "<end>";
            if (!p.equals(q)) return "first difference at line " + (i + 1);
        }
        return "same text";
    }

    /** One parsed source file. */
    final class Src {
        final Path path;
        final String text;
        final CompilationUnitTree cu;
        final SourcePositions sp;
        final String pkg;
        final Map<String, String> imports = new HashMap<>();
        final List<String> wildcards = new ArrayList<>();

        Src(Path path) throws IOException {
            this.path = path;
            JavaCompiler jc = ToolProvider.getSystemJavaCompiler();
            if (jc == null) throw new IllegalStateException("gen-docs needs a JDK (javax.tools compiler), not a JRE");
            StandardJavaFileManager fm = jc.getStandardFileManager(null, Locale.ROOT, StandardCharsets.UTF_8);
            String over = overrides.get(rel(path));
            javax.tools.JavaFileObject jfo = over == null ? fm.getJavaFileObjects(path.toFile()).iterator().next()
                    : new javax.tools.SimpleJavaFileObject(path.toUri(), javax.tools.JavaFileObject.Kind.SOURCE) {
                        @Override
                        public CharSequence getCharContent(boolean ignoreEncodingErrors) {
                            return over;
                        }
                    };
            JavacTask t = (JavacTask) jc.getTask(null, fm, d -> { }, List.of("-proc:none"), null, List.of(jfo));
            this.cu = t.parse().iterator().next();
            this.sp = Trees.instance(t).getSourcePositions();
            this.text = cu.getSourceFile().getCharContent(true).toString();
            this.pkg = cu.getPackageName() == null ? "" : cu.getPackageName().toString();
            for (ImportTree it : cu.getImports()) {
                if (it.isStatic()) continue;
                String q = it.getQualifiedIdentifier().toString();
                if (q.endsWith(".*")) wildcards.add(q.substring(0, q.length() - 2));
                else imports.put(simple(q), q);
            }
        }

        /** A type name as written in this file to a fully qualified name (null when unknown). */
        String resolve(String name) {
            if (name.contains(".")) {
                String head = name.substring(0, name.indexOf('.'));
                if (Character.isLowerCase(head.charAt(0))) return name;   // already qualified
                String outer = resolve(head);
                return outer == null ? null : outer + name.substring(head.length());
            }
            if (imports.containsKey(name)) return imports.get(name);
            String same = pkg.isEmpty() ? name : pkg + "." + name;
            if (sourceOf(same) != null) return same;
            for (String w : wildcards) if (sourceOf(w + "." + name) != null) return w + "." + name;
            return null;
        }

        ClassTree findClass(String name) {
            ClassTree[] found = new ClassTree[1];
            new TreeScanner<Void, Void>() {
                @Override
                public Void visitClass(ClassTree c, Void p) {
                    if (found[0] == null && c.getSimpleName().contentEquals(name)) found[0] = c;
                    return super.visitClass(c, p);
                }
            }.scan(cu, null);
            return found[0];
        }

        MethodTree findMethod(String cls, String name) {
            ClassTree c = findClass(cls);
            if (c == null) return null;
            for (Tree m : c.getMembers()) if (m instanceof MethodTree && ((MethodTree) m).getName().contentEquals(name)) return (MethodTree) m;
            return null;
        }

        boolean hasStaticField(String name) {
            return staticField(name) != null;
        }

        VariableTree staticField(String name) {
            VariableTree[] found = new VariableTree[1];
            new TreeScanner<Void, Void>() {
                @Override
                public Void visitVariable(VariableTree v, Void p) {
                    if (found[0] == null && v.getName().contentEquals(name) && v.getModifiers().getFlags().contains(Modifier.STATIC)) found[0] = v;
                    return null;
                }

                @Override
                public Void visitClass(ClassTree c, Void p) {
                    for (Tree m : c.getMembers()) if (m instanceof VariableTree) visitVariable((VariableTree) m, p);
                    return null;
                }
            }.scan(cu, null);
            return found[0];
        }

        /** Evaluates a static String constant built from literals, `+` and String.join(sep, <static list of literals>). */
        String evalStaticString(String name, GenDocs g) {
            VariableTree v = staticField(name);
            if (v == null || v.getInitializer() == null) return null;
            return eval(v.getInitializer());
        }

        String eval(ExpressionTree e) {
            e = unparen(e);
            if (e instanceof LiteralTree) return String.valueOf(((LiteralTree) e).getValue());
            if (e instanceof BinaryTree && e.getKind() == Tree.Kind.PLUS) {
                BinaryTree bt = (BinaryTree) e;
                return eval(bt.getLeftOperand()) + eval(bt.getRightOperand());
            }
            if (e instanceof MethodInvocationTree) {
                MethodInvocationTree mi = (MethodInvocationTree) e;
                if (mi.getMethodSelect().toString().equals("String.join") && mi.getArguments().size() == 2) {
                    List<String> items = staticList(mi.getArguments().get(1));
                    if (items == null) items = registryIds(mi.getArguments().get(1));
                    if (items != null) return String.join(eval(mi.getArguments().get(0)), items);
                }
            }
            return "<…>";
        }

        /** X.FIELD where FIELD = List.of("a", ...) / new String[] {"a", ...} / Arrays.asList(...). */
        List<String> staticList(ExpressionTree e) {
            if (!(e instanceof MemberSelectTree)) return null;
            MemberSelectTree ms = (MemberSelectTree) e;
            String fqn = resolve(ms.getExpression().toString());
            Path p = sourceOf(fqn);
            if (p == null) return null;
            try {
                VariableTree v = src(p).staticField(ms.getIdentifier().toString());
                if (v == null) return null;
                ExpressionTree init = v.getInitializer();
                List<? extends ExpressionTree> elems = null;
                if (init instanceof MethodInvocationTree) elems = ((MethodInvocationTree) init).getArguments();
                if (init instanceof NewArrayTree) elems = ((NewArrayTree) init).getInitializers();
                if (elems == null) return null;
                List<String> out = new ArrayList<>();
                for (ExpressionTree x : elems) {
                    if (!(x instanceof LiteralTree)) return null;
                    out.add(String.valueOf(((LiteralTree) x).getValue()));
                }
                return out;
            } catch (IOException ex) {
                return null;
            }
        }

        /** X.ids() where X's static block calls register(new C()) and each C has `id() { return "literal"; }`. */
        List<String> registryIds(ExpressionTree e) {
            if (!(e instanceof MethodInvocationTree) || !((MethodInvocationTree) e).getArguments().isEmpty()) return null;
            ExpressionTree sel = ((MethodInvocationTree) e).getMethodSelect();
            if (!(sel instanceof MemberSelectTree)) return null;
            Path p = sourceOf(resolve(((MemberSelectTree) sel).getExpression().toString()));
            if (p == null) return null;
            try {
                Src reg = src(p);
                List<String> out = new ArrayList<>();
                boolean[] ok = { true };
                new TreeScanner<Void, Void>() {
                    @Override
                    public Void visitMethodInvocation(MethodInvocationTree mi, Void v) {
                        if (mi.getMethodSelect().toString().equals("register") && mi.getArguments().size() == 1 && mi.getArguments().get(0) instanceof NewClassTree) {
                            String c = reg.resolve(((NewClassTree) mi.getArguments().get(0)).getIdentifier().toString());
                            String id = null;
                            try {
                                Path cp = sourceOf(c);
                                MethodTree m = cp == null ? null : src(cp).findMethod(simple(c), "id");
                                if (m != null && m.getBody() != null && m.getBody().getStatements().size() == 1
                                        && m.getBody().getStatements().get(0) instanceof com.sun.source.tree.ReturnTree) {
                                    ExpressionTree r = ((com.sun.source.tree.ReturnTree) m.getBody().getStatements().get(0)).getExpression();
                                    if (r instanceof IdentifierTree) {   // return ID; with a static String ID = "..."
                                        VariableTree k = src(cp).staticField(r.toString());
                                        if (k != null) r = k.getInitializer();
                                    }
                                    if (r instanceof LiteralTree) id = String.valueOf(((LiteralTree) r).getValue());
                                }
                            } catch (IOException ex) {
                                id = null;
                            }
                            if (id == null) ok[0] = false; else out.add(id);
                        }
                        return super.visitMethodInvocation(mi, v);
                    }
                }.scan(reg.cu, null);
                return ok[0] && !out.isEmpty() ? out : null;
            } catch (IOException ex) {
                return null;
            }
        }

        List<String> stringLiterals() {
            List<String> out = new ArrayList<>();
            new TreeScanner<Void, Void>() {
                @Override
                public Void visitLiteral(LiteralTree l, Void p) {
                    if (l.getValue() instanceof String) out.add((String) l.getValue());
                    return null;
                }
            }.scan(cu, null);
            return out;
        }

        /** The javadoc comment right before a declaration (annotations included), as plain Markdown-ready text; null if none. */
        String javadocBefore(Tree t) {
            int start = (int) sp.getStartPosition(cu, t);
            if (start < 0) return null;
            int e = start;
            while (e > 0 && Character.isWhitespace(text.charAt(e - 1))) e--;
            if (e < 2 || !text.startsWith("*/", e - 2)) return null;
            int s = text.lastIndexOf("/*", e - 2);
            if (s < 0 || !text.startsWith("/**", s)) return null;
            String body = text.substring(s + 3, e - 2);
            StringBuilder b = new StringBuilder();
            for (String l : body.split("\r?\n")) {
                l = l.replaceFirst("^\\s*\\*\\s?", "").trim();
                if (l.startsWith("@")) break;   // block tags end the description
                if (b.length() > 0) b.append(' ');
                b.append(l);
            }
            return javadocToMarkdown(b.toString());
        }
    }

    /**
     * Javadoc text to a Markdown table cell: {@code x} and {@literal x} become code spans (contents kept as written, so
     * `<ai>` survives), {@link #f} / {@link C#m} become `f` / `C.m`, HTML is dropped outside code spans, and the internal
     * work-item tags GATF's sources carry ("H1 (Δ149): ", "OA2: ", "(Δ163k)") are removed. Null when nothing is left.
     */
    static String javadocToMarkdown(String text) {
        String t = text.replaceAll("\\{@(?:code|literal)\\s+([^}]*)}", "`$1`");
        t = t.replaceAll("\\{@link(?:plain)?\\s+#([^}\\s]*)[^}]*}", "`$1`").replaceAll("\\{@link(?:plain)?\\s+([^}#\\s]*)#([^}\\s]*)[^}]*}", "`$1.$2`")
                .replaceAll("\\{@link(?:plain)?\\s+([^}\\s]*)[^}]*}", "`$1`");
        StringBuilder out = new StringBuilder();
        String[] parts = t.split("`", -1);
        for (int i = 0; i < parts.length; i++) {
            if (i > 0) out.append('`');
            out.append(i % 2 == 0 ? parts[i].replaceAll("<[^>]+>", "") : parts[i]);
        }
        String r = out.toString().replaceAll("\\s+", " ").trim();
        r = r.replaceFirst("^(?:[A-Z]{1,3}\\d+[a-z]?(?:\\s*\\(Δ\\d+[a-z]?\\))?|Δ\\d+[a-z]?)\\s*:\\s*", "").replaceAll("\\s*\\(Δ\\d+[a-z]?\\)", "");
        if (!r.isEmpty()) r = Character.toUpperCase(r.charAt(0)) + r.substring(1);
        return r.isEmpty() ? null : r;
    }

    // ------------------------------------------------------------------------------------------------ tiny JSON reader

    /** Enough JSON for commands.json (objects, arrays, strings, numbers, booleans, null). */
    static final class Json {
        final String s;
        int i;

        Json(String s) {
            this.s = s;
        }

        Object parse() {
            Object o = value();
            ws();
            if (i != s.length()) throw new IllegalArgumentException("trailing JSON at " + i);
            return o;
        }

        void ws() {
            while (i < s.length() && Character.isWhitespace(s.charAt(i))) i++;
        }

        Object value() {
            ws();
            char c = s.charAt(i);
            if (c == '{') {
                Map<String, Object> m = new LinkedHashMap<>();
                i++;
                ws();
                if (s.charAt(i) == '}') { i++; return m; }
                while (true) {
                    ws();
                    String k = string();
                    ws();
                    expect(':');
                    m.put(k, value());
                    ws();
                    if (s.charAt(i) == ',') { i++; continue; }
                    expect('}');
                    return m;
                }
            }
            if (c == '[') {
                List<Object> l = new ArrayList<>();
                i++;
                ws();
                if (s.charAt(i) == ']') { i++; return l; }
                while (true) {
                    l.add(value());
                    ws();
                    if (s.charAt(i) == ',') { i++; continue; }
                    expect(']');
                    return l;
                }
            }
            if (c == '"') return string();
            if (s.startsWith("true", i)) { i += 4; return Boolean.TRUE; }
            if (s.startsWith("false", i)) { i += 5; return Boolean.FALSE; }
            if (s.startsWith("null", i)) { i += 4; return null; }
            int st = i;
            while (i < s.length() && "+-0123456789.eE".indexOf(s.charAt(i)) >= 0) i++;
            if (st == i) throw new IllegalArgumentException("bad JSON at " + i);
            return Double.valueOf(s.substring(st, i));
        }

        void expect(char c) {
            if (s.charAt(i) != c) throw new IllegalArgumentException("expected " + c + " at " + i);
            i++;
        }

        String string() {
            expect('"');
            StringBuilder b = new StringBuilder();
            while (true) {
                char c = s.charAt(i++);
                if (c == '"') return b.toString();
                if (c == '\\') {
                    char n = s.charAt(i++);
                    switch (n) {
                        case 'n': b.append('\n'); break;
                        case 't': b.append('\t'); break;
                        case 'r': b.append('\r'); break;
                        case 'b': b.append('\b'); break;
                        case 'f': b.append('\f'); break;
                        case 'u': b.append((char) Integer.parseInt(s.substring(i, i + 4), 16)); i += 4; break;
                        default: b.append(n);
                    }
                } else {
                    b.append(c);
                }
            }
        }
    }
