    String renderModel(String page, String title, int pos, String descFile, String rootFqn, String intro) throws IOException {
        StringBuilder b = new StringBuilder(frontMatter(title, pos));
        b.append("# ").append(title).append("\n\n").append(String.format(GEN_NOTE, descFile)).append("\n\n").append(intro).append("\n");
        List<String> order = new ArrayList<>();
        Map<String, TypeInfo> types = new LinkedHashMap<>();
        collectTypes(rootFqn, types, order);
        // contents
        b.append("Types on this page: ");
        List<String> links = new ArrayList<>();
        for (String fqn : order) links.add("[`" + simple(fqn) + "`](#" + slug(simple(fqn)) + ")");
        b.append(String.join(" · ", links)).append("\n");
        for (String fqn : order) {
            TypeInfo t = types.get(fqn);
            String cls = simple(fqn);
            b.append("\n## ").append(cls).append("\n\n");
            String cdesc = describe(descFile, cls, t.javadoc);
            b.append(cdesc == null ? "**Undocumented.**" : cdesc);
            if (t.xmlRoot != null) b.append(" XML root element: `<").append(t.xmlRoot).append(">`.");
            b.append(" Source: [`").append(cls).append(".java`](").append(GITHUB_BLOB).append(rel(t.src.path)).append(").\n\n");
            if (cdesc == null) problems.add(descFile + ": no description for type " + cls);
            if (t.isEnum) {
                b.append("| Value | Description |\n|---|---|\n");
                for (String c : t.enumConstants) {
                    String d = describe(descFile, cls + "." + c, null);
                    if (d == null) problems.add(descFile + ": no description for " + cls + "." + c);
                    b.append("| `").append(c).append("` | ").append(cell(d == null ? "**Undocumented.**" : d)).append(" |\n");
                }
                continue;
            }
            List<String[]> internal = new ArrayList<>();
            b.append("| Field | Type | Default | Description |\n|---|---|---|---|\n");
            for (FieldInfo f : t.fields) {
                String d = describe(descFile, cls + "." + f.name, f.javadoc);
                if (d == null) {
                    problems.add(descFile + ": no description for " + cls + "." + f.name
                            + " (add javadoc on the field, or a line `" + cls + "." + f.name + "=...` to tools/gen-docs/descriptions/" + descFile + ")");
                    d = "**Undocumented.**";
                }
                if (d.startsWith("@internal")) {
                    internal.add(new String[] { f.name, d.substring("@internal".length()).replaceFirst("^[:\\s]+", "") });
                    continue;
                }
                b.append("| `").append(f.name).append("` | ").append(typeCell(f, types)).append(" | ").append(f.defaultText)
                        .append(" | ").append(cell(d)).append(" |\n");
            }
            if (!t.aliases.isEmpty()) {
                b.append("\nAlso accepted when reading a file (setter names that differ from the field):\n\n| Name | Same as |\n|---|---|\n");
                for (Map.Entry<String, String> al : t.aliases.entrySet()) {
                    String d = al.getValue() != null ? "`" + al.getValue() + "`" : describe(descFile, cls + "." + al.getKey(), null);
                    if (d == null) problems.add(descFile + ": no description for setter-only property " + cls + "." + al.getKey());
                    b.append("| `").append(al.getKey()).append("` | ").append(cell(d == null ? "**Undocumented.**" : d)).append(" |\n");
                }
            }
            if (!internal.isEmpty()) {
                b.append("\nAlso serialized, but not meant to be set in a config file:\n\n| Field | Why |\n|---|---|\n");
                for (String[] r : internal) b.append("| `").append(r[0]).append("` | ").append(cell(r[1])).append(" |\n");
            }
        }
        return b.toString();
    }

    String typeCell(FieldInfo f, Map<String, TypeInfo> types) {
        String t = f.typeText;
        for (String fqn : f.refs) {
            if (types.containsKey(fqn)) {
                String s = simple(fqn);
                return "[`" + t.replace(fqn, s) + "`](#" + slug(s) + ")";
            }
        }
        return "`" + t + "`";
    }

    static final class TypeInfo {
        Src src;
        String javadoc;
        String xmlRoot;
        boolean isEnum;
        List<FieldInfo> fields = new ArrayList<>();
        List<String> enumConstants = new ArrayList<>();
        /** Setter-only property names Jackson also binds (name -> the field the setter assigns, or null). */
        Map<String, String> aliases = new LinkedHashMap<>();
    }

    static final class FieldInfo {
        String name;
        String typeText;
        String defaultText;
        String javadoc;
        List<String> refs = new ArrayList<>();
    }

    void collectTypes(String fqn, Map<String, TypeInfo> types, List<String> order) throws IOException {
        if (types.containsKey(fqn)) return;
        Path p = sourceOf(fqn);
        if (p == null) return;
        Src s = src(p);
        ClassTree ct = s.findClass(simple(fqn));
        if (ct == null) return;
        TypeInfo t = new TypeInfo();
        t.src = s;
        t.javadoc = s.javadocBefore(ct);
        t.isEnum = ct.getKind() == Tree.Kind.ENUM;
        for (AnnotationTree a : ct.getModifiers().getAnnotations()) {
            if (annName(a).equals("JacksonXmlRootElement")) t.xmlRoot = annArg(a, "localName");
        }
        types.put(fqn, t);
        order.add(fqn);
        List<String> nested = new ArrayList<>();
        for (Tree m : ct.getMembers()) {
            if (!(m instanceof VariableTree)) continue;
            VariableTree v = (VariableTree) m;
            if (t.isEnum && v.getInitializer() instanceof NewClassTree && v.getType() != null && v.getType().toString().equals(ct.getSimpleName().toString())) {
                t.enumConstants.add(v.getName().toString());
                continue;
            }
            Set<Modifier> mods = v.getModifiers().getFlags();
            if (mods.contains(Modifier.STATIC) || mods.contains(Modifier.TRANSIENT)) continue;
            String name = v.getName().toString();
            boolean ignored = false;
            for (AnnotationTree a : v.getModifiers().getAnnotations()) {
                String an = annName(a);
                if (an.equals("JsonIgnore")) ignored = true;
                if (an.equals("JsonProperty")) {
                    String n = annArg(a, "value");
                    if (n != null && !n.isEmpty()) name = n;
                }
            }
            if (ignored || t.isEnum) continue;
            FieldInfo f = new FieldInfo();
            f.name = name;
            f.typeText = v.getType().toString();
            f.javadoc = s.javadocBefore(v);
            f.defaultText = defaultText(v);
            collectRefs(v.getType(), s, f.refs);
            for (String r : f.refs) if (!nested.contains(r)) nested.add(r);
            t.fields.add(f);
        }
        // setter-only names: Jackson (setterVisibility default) binds public setX(..) as property "x" even without a field x
        Set<String> fieldNames = new HashSet<>();
        for (Tree m : ct.getMembers()) if (m instanceof VariableTree) fieldNames.add(((VariableTree) m).getName().toString());
        for (Tree m : ct.getMembers()) {
            if (!(m instanceof MethodTree) || t.isEnum) continue;
            MethodTree mt = (MethodTree) m;
            String mn = mt.getName().toString();
            Set<Modifier> mods = mt.getModifiers().getFlags();
            if (!mn.startsWith("set") || mn.length() == 3 || mt.getParameters().size() != 1 || !mods.contains(Modifier.PUBLIC) || mods.contains(Modifier.STATIC)) continue;
            boolean ignored = false;
            for (AnnotationTree a : mt.getModifiers().getAnnotations()) if (annName(a).equals("JsonIgnore")) ignored = true;
            String prop = jacksonName(mn.substring(3));
            if (ignored || fieldNames.contains(prop)) continue;
            String[] target = { null };
            if (mt.getBody() != null) new TreeScanner<Void, Void>() {
                @Override
                public Void visitAssignment(com.sun.source.tree.AssignmentTree as, Void p) {
                    String v = as.getVariable().toString();
                    if (v.startsWith("this.")) v = v.substring(5);
                    if (target[0] == null && fieldNames.contains(v)) target[0] = v;
                    return super.visitAssignment(as, p);
                }
            }.scan(mt.getBody(), null);
            t.aliases.put(prop, target[0]);
        }
        for (String r : nested) collectTypes(r, types, order);
    }

    /** Jackson's default (legacy) property name for a setter suffix: the leading upper-case run is lower-cased. */
    static String jacksonName(String suffix) {
        StringBuilder b = new StringBuilder();
        int i = 0;
        while (i < suffix.length() && Character.isUpperCase(suffix.charAt(i))) b.append(Character.toLowerCase(suffix.charAt(i++)));
        return b.append(suffix.substring(i)).toString();
    }

    void collectRefs(Tree type, Src s, List<String> out) {
        if (type == null) return;
        if (type instanceof ArrayTypeTree) {
            collectRefs(((ArrayTypeTree) type).getType(), s, out);
        } else if (type instanceof ParameterizedTypeTree) {
            ParameterizedTypeTree pt = (ParameterizedTypeTree) type;
            collectRefs(pt.getType(), s, out);
            for (Tree a : pt.getTypeArguments()) collectRefs(a, s, out);
        } else if (type instanceof IdentifierTree || type instanceof MemberSelectTree) {
            String fqn = s.resolve(type.toString());
            if (fqn != null && fqn.startsWith("com.gatf.") && sourceOf(fqn) != null) out.add(fqn);
        }
    }

    static String defaultText(VariableTree v) {
        ExpressionTree init = v.getInitializer();
        if (init == null) {
            if (v.getType() instanceof PrimitiveTypeTree) {
                String t = v.getType().toString();
                return t.equals("boolean") ? "`false`" : "`0`";
            }
            return "*(unset)*";
        }
        if (init instanceof LiteralTree) {
            Object val = ((LiteralTree) init).getValue();
            return val == null ? "*(unset)*" : "`" + val + "`";
        }
        if (init instanceof NewArrayTree || init instanceof NewClassTree) return "empty";
        String s = init.toString();
        if (s.matches("-?\\d+[lLfFdD]?")) s = s.replaceAll("[lLfFdD]$", "");
        return "`" + s + "`";
    }

