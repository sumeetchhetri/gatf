// Δ148: one source for the semantic resolver. Copies SemanticLocators.RESOLVER_FN, CANDIDATES_FN and FALLBACK_FN out
// of the Java text blocks, verbatim, into frontend/src/trace/semanticResolver.generated.js, so the Trace Viewer's
// pick-locator runs the very script the recorder and the runtime inject into pages.
//   node tools/gen-semantic-resolver.mjs           write the module
//   node tools/gen-semantic-resolver.mjs --check   exit 1 when the module is stale
// Drift is also caught by SemanticResolverSyncTest (JUnit, exact Java constants) and semanticResolver.test.ts (vitest).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const JAVA = resolve(here, '../alldep-jar/src/main/java/com/gatf/selenium/SemanticLocators.java');
export const OUT = resolve(here, '../frontend/src/trace/semanticResolver.generated.js');
export const BLOCKS = ['RESOLVER_FN', 'CANDIDATES_FN', 'FALLBACK_FN'];

/**
 * A Java text block's value: incidental indentation (common to the content lines and the closing delimiter line)
 * stripped, trailing spaces removed, then escapes processed. The blocks use \\ only (and must keep doing so); any
 * other escape is refused, so a new one cannot be copied wrong silently.
 */
export function textBlock(src, name) {
  const m = src.match(new RegExp('\\b' + name + '\\s*=\\s*"""[ \\t]*\\r?\\n([\\s\\S]*?)"""'));
  if (!m) throw new Error('text block ' + name + ' not found in SemanticLocators.java');
  const lines = m[1].replace(/\r/g, '').split('\n');
  const closing = lines[lines.length - 1];
  if (closing.trim() !== '') throw new Error(name + ': the closing """ must be on its own line');
  const ind = Math.min(closing.length, ...lines.slice(0, -1).filter((l) => l.trim()).map((l) => l.match(/^[ \t]*/)[0].length));
  const body = lines.slice(0, -1).map((l) => l.slice(ind).replace(/[ \t]+$/, '')).join('\n') + '\n';
  return body.replace(/\\([\s\S])/g, (_, c) => {
    if (c === '\\') return '\\';
    throw new Error(name + ': unsupported escape \\' + c + ' (use \\\\ only)');
  });
}

const HEADER = readFileSync(fileURLToPath(import.meta.url), 'utf8').match(/^\/\*[\s\S]*?\*\/\n/)[0];

export function render(src) {
  let out = HEADER +
    '// GENERATED by tools/gen-semantic-resolver.mjs from SemanticLocators.java (' + BLOCKS.join(', ') + '). Do not edit:\n' +
    '// change the Java text blocks and run `node tools/gen-semantic-resolver.mjs`. SemanticResolverSyncTest (JUnit) and\n' +
    '// semanticResolver.test.ts (vitest) fail when this file and the Java source diverge.\n' +
    '// The page script runs verbatim inside a factory whose `document` and `window` are parameters, so the viewer calls it\n' +
    '// in its own realm against a snapshot document (the sandboxed snapshot frame itself never runs script).\n' +
    'export function makeSemanticResolver(document, window) {\n';
  for (const b of BLOCKS) out += '// ---- ' + b + ' ----\n' + textBlock(src, b);
  out += '// ---- end ----\n';
  out += '  return { semantic: __gatfSemantic, candidates: __gatfCandidates, fallback: __gatfFallback };\n}\n';
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = render(readFileSync(JAVA, 'utf8'));
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch { /* missing = stale */ }
    if (have !== want) { console.error('stale: ' + OUT + ' (run node tools/gen-semantic-resolver.mjs)'); process.exit(1); }
    console.log('semantic resolver module up to date');
  } else {
    writeFileSync(OUT, want);
    console.log('wrote ' + OUT);
  }
}
