// Apache-2.0 header tool for the GATF repo (dependency-free Node).
//
//   node tools/license/license-headers.mjs            apply: add the header / normalize an older one
//   node tools/license/license-headers.mjs --check    CI: exit 1 listing files missing the exact header
//   ... --verbose                                     also list skipped files with the reason
//
// SOURCE CODE files only (Java, TS/JS, CSS, shell, PowerShell, Python); docs, markup, config,
// templates and .sel scripts are not touched. The header goes after any shebang / Python coding line. Files carrying a third-party copyright or license (GPL/LGPL, MIT,
// BSD, …) are NEVER relabelled — they are skipped and reported. JSON, binaries, lockfiles, generated
// files and runtime/scratch dirs are skipped (no comment syntax / not source). Line endings are
// preserved (CRLF files stay CRLF).

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, basename, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SELF = fileURLToPath(import.meta.url); // this file names the foreign markers — don't self-flag
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const YEARS = '2013-2026';
const OWNER = 'Sumeet Chhetri';

// The canonical text (body lines, without comment delimiters).
const BODY = [
  `Copyright ${YEARS}, ${OWNER}`,
  '',
  'Licensed under the Apache License, Version 2.0 (the "License");',
  'you may not use this file except in compliance with the License.',
  'You may obtain a copy of the License at',
  '',
  'http://www.apache.org/licenses/LICENSE-2.0',
  '',
  'Unless required by applicable law or agreed to in writing, software',
  'distributed under the License is distributed on an "AS IS" BASIS,',
  'WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.',
  'See the License for the specific language governing permissions and',
  'limitations under the License.',
];

const indent = (l) => (l ? '    ' + l : '');
const STYLES = {
  block: () => ['/*', ...BODY.map(indent), '*/'],
  hash: () => BODY.map((l) => (l ? '#    ' + l : '#')),
};

// Source code only (delta-075 rev): markup/docs (md, xml, html), config (yml, properties, props,
// Dockerfile), templates (.vm), grammars (.ebnf) and seleasy test scripts (.sel) are left untouched.
const EXT_STYLE = {
  '.java': 'block', '.ts': 'block', '.tsx': 'block', '.js': 'block', '.mjs': 'block', '.cjs': 'block',
  '.jsx': 'block', '.css': 'block', '.scss': 'block', '.less': 'block', '.groovy': 'block', '.kt': 'block',
  '.sh': 'hash', '.bash': 'hash', '.py': 'hash', '.ps1': 'hash',
};
const styleFor = (name) => EXT_STYLE[extname(name).toLowerCase()];

// Runtime / scratch / build / vendored dirs — never source.
const SKIP_DIRS = new Set([
  'node_modules', '.git', 'dist', 'target', '.mvn-node', 'test-results', 'playwright-report', 'out',
  'tmp', 'temp', 'private', 'test-output', '.settings', '.idea', '.vscode', '.X11-unix', 'hsperfdata_seluser',
  'export-corpus',   // Δ161a: exported goldens (.spec.ts / Test.java) are generated output, like codegen-golden
]);
const SKIP_FILES = new Set(['dependency-reduced-pom.xml', 'LICENSE', 'NOTICE']); // generated by shade / the license itself

// Third-party markers: any of these (or a Copyright line not naming the owner) → leave the file alone.
const FOREIGN = /Free Software Foundation|GNU (Lesser )?General Public|MIT License|Permission is hereby granted|BSD License|Redistribution and use in source and binary forms|Mozilla Public License|Eclipse Public License/i;
const GENERATED = /@generated|DO NOT EDIT/;

function* walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name) && !e.name.startsWith('.')) yield* walk(join(dir, e.name));
      else if (e.name === '.github') yield* walk(join(dir, e.name)); // workflows are source
    } else if (e.isFile()) yield join(dir, e.name);
  }
}

// Return {status, text?, reason?} for one file.
function processFile(path) {
  const name = basename(path);
  if (SKIP_FILES.has(name) || (name.startsWith('.') && !path.includes('/.github/'))) return { status: 'skip', reason: 'dotfile/generated' };
  const style = styleFor(name);
  if (!style) return { status: 'skip', reason: 'no comment syntax (' + (extname(name) || name) + ')' };
  if (statSync(path).size > 2_000_000) return { status: 'skip', reason: 'large file' };
  const raw = readFileSync(path, 'utf8');
  if (raw.includes('\u0000')) return { status: 'skip', reason: 'binary' };

  const foreignCopyright = raw.split(/\r?\n/).some((l) => /Copyright\s*(\(c\)|©|\d)/i.test(l) && !l.includes(OWNER));
  if (path !== SELF && (FOREIGN.test(raw.slice(0, 20000)) || foreignCopyright)) return { status: 'skip', reason: 'third-party license/copyright' };
  if (GENERATED.test(raw.slice(0, 2000))) return { status: 'skip', reason: 'generated' };

  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const bom = raw.startsWith('\uFEFF') ? '\uFEFF' : '';
  let lines = (bom ? raw.slice(1) : raw).split(/\r?\n/);
  const header = STYLES[style]();

  // Preamble lines that must stay first.
  let pre = 0;
  if (lines[0]?.startsWith('#!')) pre = 1;
  if (style === 'hash' && extname(name) === '.py' && /coding[:=]/.test(lines[pre] ?? '')) pre++;

  // Already exact?
  const at = lines.slice(pre, pre + header.length).join('\n');
  if (at === header.join('\n')) return { status: 'ok' };

  // An older/variant header of ours (e.g. "Copyright 2013-2019") directly after the preamble → replace it.
  // Delimited styles: the old block spans the opener at `pre` to its closing delimiter (any wording/reflow).
  const DELIM = { block: [/^\s*\/\*/, /\*\/\s*$/] }[style];
  let oldEnd = -1;
  if (DELIM && DELIM[0].test(lines[pre] ?? '')) {
    for (let i = pre; i < Math.min(lines.length, pre + 40); i++) if (DELIM[1].test(lines[i])) { oldEnd = i; break; }
  } else if (!DELIM) {
    // line-comment styles (#, //): the contiguous comment run at `pre`
    const lc = /^\s*#/;
    let i = pre;
    while (i < lines.length && lc.test(lines[i])) i++;
    if (i > pre) oldEnd = i - 1;
  }
  if (oldEnd >= 0) {
    const block = lines.slice(pre, oldEnd + 1).join('\n');
    if (block.includes(OWNER) && /Apache License/.test(block)) {
      lines = [...lines.slice(0, pre), ...header, ...lines.slice(oldEnd + 1)];
      return { status: 'update', text: bom + lines.join(eol) };
    }
  }
  lines = [...lines.slice(0, pre), ...header, ...lines.slice(pre)];
  return { status: 'add', text: bom + lines.join(eol) };
}

const check = process.argv.includes('--check');
const verbose = process.argv.includes('--verbose');
const tally = { ok: 0, add: 0, update: 0, skip: 0 };
const need = [];
for (const f of walk(ROOT)) {
  const r = processFile(f);
  const rel = relative(ROOT, f);
  tally[r.status]++;
  if (r.status === 'skip') {
    if (verbose || r.reason === 'third-party license/copyright') console.log(`skip  ${rel}  (${r.reason})`);
  } else if (r.status !== 'ok') {
    need.push(rel);
    if (!check) writeFileSync(f, r.text);
    if (verbose || check) console.log(`${check ? 'MISSING' : r.status}  ${rel}`);
  }
}
console.log(`\n${check ? 'check' : 'applied'}: ${tally.ok} ok, ${tally.add} added, ${tally.update} normalized, ${tally.skip} skipped`);
if (check && need.length) {
  console.error(`${need.length} file(s) lack the exact Apache-2.0 header — run: node tools/license/license-headers.mjs`);
  process.exit(1);
}
