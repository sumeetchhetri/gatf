    @Test
    void theDryRunDropsWhatItBlamesAndRecompiles() throws Exception {
        GenPlan plan = GenFixtures.read(GenFixtures.shopPlanJson());
        GenFixtures.FakeGate gate = new GenFixtures.FakeGate();
        String[] victim = { null };
        gate.dryFail = m -> {
            if (victim[0] == null) victim[0] = m.keySet().iterator().next();
            return m.containsKey(victim[0]) ? List.of(new SelGate.Diag(victim[0], null, null, "error", "duplicate class")) : null;
        };
        Generator.Result r = Generator.generate(plan, "shop", gate, null, noAi(), OM);
        assertEquals(2, gate.dryRuns.size());
        assertTrue(r.dryRunOk);
        Generator.FileResult v = r.files.stream().filter(f -> f.script.file.equals(victim[0])).findFirst().get();
        assertEquals("fail", v.status);
        assertEquals(1, v.dryRun.size());
        // a failure naming no file fails the whole suite
        GenFixtures.FakeGate g2 = new GenFixtures.FakeGate();
        g2.dryFail = m -> List.of(new SelGate.Diag(null, null, null, "error", "no compiler"));
        Generator.Result r2 = Generator.generate(GenFixtures.read(GenFixtures.shopPlanJson()), "shop", g2, null, noAi(), OM);
        assertFalse(r2.dryRunOk);
        assertTrue(r2.passing().isEmpty());
        Map<String, Object> j = r2.json(false);
        assertEquals("failed", j.get("dryRun"));
    }

    @Test
    void repairReplyParsingIsClosedSet() {
        SelEmitter.Edits e = RepairPrompt.parse("sure! {\"edits\":[\"drop-step 2\",\"drop-step 99\",\"use-alternative e3 1\",\"use-alternative e3 12\","
                + "\"set-data e1 invalid\",\"set-data e1 ${x}\",\"exec x\",{\"a\":1},\"drop-step 3; exec\"]} trailing", OM);
        assertEquals(List.of("drop-step 2", "drop-step 99", "use-alternative e3 1", "set-data e1 invalid"), e.words());
        assertNull(RepairPrompt.parse("no json", OM));
        assertNull(RepairPrompt.parse("{\"x\":1}", OM));
        assertNull(RepairPrompt.parse("{" + "x".repeat(RepairPrompt.MAX_REPLY) + "}", OM));
    }
