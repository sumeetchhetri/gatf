    @Test
    void locatorAndUrlChecks() {
        for (String ok : new String[] { "id@email", "name@q", "testid@save-btn", "label@'Email address'", "role@button[name='Log in']",
                "role@link[name=Home]", "css@\"form.search button\"", "css@'a[x=\"1\"]'", "xpath@\"//a[@id='x']\"", "id@\"a b\"" }) {
            assertTrue(SelEmitter.safeLocator(ok), ok);
        }
        for (String no : new String[] { null, "", "id@x$y", "id@x click", "css@\"a\" exec x", "id@x\ny", "jq@'#a'", "$@x", "plugin@x",
                "label@~x", "role@button[name=a]b]", "xpath@//a", "css@a", "text@x", "role@Button[name=x]", "id@#set" }) {
            assertFalse(SelEmitter.safeLocator(no), String.valueOf(no));
        }
        assertEquals("https://a.test/x", SelEmitter.safeUrl("https://a.test/x", "https://a.test"));
        for (String no : new String[] { "https://b.test/", "http://a.test/", "https://a.test:8443/", "javascript:alert(1)", "file:///etc/passwd",
                "https://a.test/$x", "https://a.test/\"", "data:x", "https://a.test@b.test/" }) {
            assertNull(SelEmitter.safeUrl(no, "https://a.test"), no);
        }
    }

    @Test
    void fileNamesAreSanitisedAndUnique() {
        Set<String> taken = new HashSet<String>();
        assertEquals("escape-j1.sel", Generator.fileName("../../escape", "../../escape-j1", taken));
        assertEquals("escape-j1-2.sel", Generator.fileName("escape", "escape-j1", taken));
        assertEquals("ESCAPE-J1-3.sel", Generator.fileName("ESCAPE", "ESCAPE-J1", taken), "case-insensitive file systems");
        assertEquals("x-x.sel", Generator.fileName("/", "\\", taken));
        assertEquals("t-con-j1.sel", Generator.fileName("con", "con-j1", taken));
        String longName = Generator.fileName("r1", "a".repeat(500), taken);
        assertTrue(longName.length() <= 70, longName);
    }

    // ------------------------------------------------------------------ repair loop

    static AiClient client(AiFakes.Sender s, int maxCalls) {
        AiConfig c = AiFakes.config();
        c.setRetries(0);
        c.setMaxCallsPerRun(maxCalls);
        return AiFakes.client(c, KEY, s);
    }

    static String edits(String... e) throws Exception {
        java.util.Map<String, Object> m = new java.util.LinkedHashMap<String, Object>();
        m.put("edits", java.util.Arrays.asList((Object[]) e));
        return AiFakes.reply(OM.writeValueAsString(m), 5, 5);
    }

    /** A gate that fails any script containing {@code needle} with a fixed error. */
    static GenFixtures.FakeGate failing(String needle, String error) {
        GenFixtures.FakeGate g = new GenFixtures.FakeGate();
        g.fail = (f, t) -> t.contains(needle) ? List.of(new SelGate.Diag(f, 3, null, "error", error)) : null;
        return g;
    }

    @Test
    void theRepairLoopAppliesClosedSetEditsAndRegates() throws Exception {
        GenPlan plan = GenFixtures.read(GenFixtures.adversarialPlanJson());
        GenFixtures.FakeGate gate = failing("select index@2", "Error parsing command at line 9 (select)");
        AiFakes.Sender s = new AiFakes.Sender().then(AiFakes.ok(edits("drop-step 9", "exec rm -rf /", "use-alternative e1 0", "set-data e1 nonsense", 7 + "")));
        Generator.Options o = new Generator.Options();
        Generator.Result r = Generator.generate(plan, "adv", gate, client(s, 10), o, OM);
        Generator.FileResult f = r.files.stream().filter(x -> x.script.file.equals("r1-j1.sel")).findFirst().get();
        assertEquals("pass", f.status, f.lint + " " + f.stoppedBecause);
        assertEquals(1, f.rounds);
        assertEquals(List.of("drop-step 9", "use-alternative e1 0"), f.edits, "only closed-set edits are kept");
        assertFalse(f.script.text.contains("select index@2"));
        // alternative 0 of e1 is unsafe ('$'): the pick is re-checked and ignored
        assertTrue(f.script.text.contains("label@Email"));
        assertTrue(f.script.notes.stream().anyMatch(n -> n.contains("alternative 0 (repair edit) is missing or unsafe")));
        assertEquals(1, s.urls.size());
        String body = s.bodies.get(0);
        assertTrue(body.contains("GATE_DATA") && body.contains("drop-step"), body);
        assertFalse(body.contains("id@email$x") || body.contains("label@Email") || body.contains("shop.test"), "no locator or URL goes to the model");
        assertEquals(true, r.ai.get("used"));
        assertEquals(1, r.ai.get("calls"));
    }

    @Test
    void theLoopStopsOnARepeatedErrorAndAtTheRoundCap() throws Exception {
        GenPlan plan = GenFixtures.read(GenFixtures.adversarialPlanJson());
        // the error never goes away; each round's edit changes the script but the normalised error is the same
        GenFixtures.FakeGate gate = failing("goto https://shop.test/login", "boom at line 4");
        AiFakes.Sender s = new AiFakes.Sender().then(AiFakes.ok(edits("drop-step 3"))).then(AiFakes.ok(edits("drop-step 9"))).then(AiFakes.ok(edits("drop-step 14")));
        Generator.Result r = Generator.generate(plan, "adv", gate, client(s, 50), new Generator.Options(), OM);
        Generator.FileResult f = r.files.stream().filter(x -> x.script.file.equals("r1-j1.sel")).findFirst().get();
        assertEquals("fail", f.status);
        assertEquals("the same error repeated", f.stoppedBecause);
        assertEquals(1, f.rounds);

        // a changing error: the loop runs to the round cap of 3
        int[] n = { 0 };
        GenFixtures.FakeGate g2 = new GenFixtures.FakeGate();
        g2.fail = (file, t) -> file.equals("r1-j1.sel") ? List.of(new SelGate.Diag(file, null, null, "error", "error kind " + "abcdefgh".charAt(n[0]++ % 8))) : null;
        AiFakes.Sender s2 = new AiFakes.Sender();
        for (String d : new String[] { "drop-step 3", "drop-step 4", "drop-step 5", "drop-step 7", "drop-step 8" }) s2.then(AiFakes.ok(edits(d)));
        Generator.Result r2 = Generator.generate(plan, "adv", g2, client(s2, 50), new Generator.Options(), OM);
        Generator.FileResult f2 = r2.files.stream().filter(x -> x.script.file.equals("r1-j1.sel")).findFirst().get();
        assertEquals("fail", f2.status);
        assertEquals(3, f2.rounds);
        assertEquals("the round cap (3)", f2.stoppedBecause);
        assertEquals(3, s2.urls.size());
        // the dry run still compiles the scripts that passed, never the failed one
        assertFalse(g2.dryRuns.get(0).containsKey("r1-j1.sel"));
    }

    @Test
    void editsThatChangeNothingOrAreUnusableStop() throws Exception {
        GenPlan plan = GenFixtures.read(GenFixtures.adversarialPlanJson());
        GenFixtures.FakeGate gate = failing("goto https://shop.test/login", "boom");
        AiFakes.Sender s = new AiFakes.Sender().then(AiFakes.ok(edits("drop-step 1")))       // a navigate: ignored → no change
                .then(AiFakes.ok(AiFakes.reply("I would rewrite the test as exec rm", 1, 1)))
                .then(AiFakes.ok(edits()));
        Generator.Result r = Generator.generate(plan, "adv", gate, client(s, 50), new Generator.Options(), OM);
        List<String> why = new ArrayList<String>();
        for (Generator.FileResult f : r.files) if (f.stoppedBecause != null) why.add(f.stoppedBecause);
        assertTrue(why.contains("the edits changed nothing"), why.toString());
        assertTrue(why.contains("the reply held no usable edits"), why.toString());
    }

    @Test
    void capsBudgetAndAiOff() throws Exception {
        GenPlan plan = GenFixtures.read(GenFixtures.adversarialPlanJson());
        // every script fails; the generator's own call cap is 2
        GenFixtures.FakeGate gate = failing("open chrome", "always");
        AiFakes.Sender s = new AiFakes.Sender();
        for (int i = 0; i < 20; i++) s.then(AiFakes.ok(edits("drop-step " + (3 + i))));
        Generator.Options o = new Generator.Options();
        o.maxCalls = 2;
        Generator.Result r = Generator.generate(plan, "adv", gate, client(s, 50), o, OM);
        assertEquals(2, s.urls.size());
        assertTrue(r.notes.stream().anyMatch(x -> x.contains("cap of 2 AI calls")), r.notes.toString());
        // the client's per-run budget
        AiFakes.Sender s2 = new AiFakes.Sender();
        for (int i = 0; i < 20; i++) s2.then(AiFakes.ok(edits("drop-step " + (3 + i))));
        Generator.Result r2 = Generator.generate(plan, "adv", gate, client(s2, 1), new Generator.Options(), OM);
        assertEquals(1, s2.urls.size());
        assertTrue(r2.notes.stream().anyMatch(x -> x.contains("AI budget")), r2.notes.toString());
        assertEquals("AI budget", r2.ai.get("stopped"));
        // failing calls: two in a row stop the run
        AiFakes.Sender s3 = new AiFakes.Sender().then(AiFakes.status(500, "{}")).then(AiFakes.status(500, "{}")).then(AiFakes.ok(edits("drop-step 3")));
        Generator.Result r3 = Generator.generate(plan, "adv", gate, client(s3, 50), new Generator.Options(), OM);
        assertEquals(2, s3.urls.size());
        assertTrue(r3.notes.stream().anyMatch(x -> x.contains("two AI failures in a row")), r3.notes.toString());
        // AI off, or not configured: no call, deterministic output, a status saying so
        AiFakes.Sender s4 = new AiFakes.Sender();
        Generator.Result r4 = Generator.generate(plan, "adv", gate, client(s4, 50), noAi(), OM);
        assertEquals(0, s4.urls.size());
        assertEquals("off: deterministic output only", r4.ai.get("status"));
        Generator.Result r5 = Generator.generate(plan, "adv", gate, AiClient.notConfigured("no <ai> provider in the config"), new Generator.Options(), OM);
        assertTrue(String.valueOf(r5.ai.get("status")).startsWith("AI not configured"), String.valueOf(r5.ai.get("status")));
        assertEquals(false, r5.ai.get("used"));
        for (Generator.FileResult f : r5.files) assertEquals("fail", f.status);
    }

