package com.gatf.ai.plan;

import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * H1 (Δ151): the Markdown view of a plan, rendered from its JSON ({@link TestPlan#toJson}), so the two never disagree.
 * Crawled text is escaped for Markdown and HTML ({@link #md}): a page title cannot open a link, an image, a code span
 * or a tag in a viewer. Routes are listed by priority, then in crawl order. Pure.
 */
public final class PlanMarkdown {

    private PlanMarkdown() {}

    @SuppressWarnings("unchecked")
    public static String render(Map<String, Object> plan) {
        StringBuilder b = new StringBuilder();
        Map<String, Object> src = (Map<String, Object>) plan.get("source");
        Map<String, Object> ai = (Map<String, Object>) plan.get("ai");
        Map<String, Object> counts = (Map<String, Object>) plan.get("counts");
        List<Map<String, Object>> routes = (List<Map<String, Object>>) plan.get("routes");
        b.append("# Test plan: ").append(md(String.valueOf(src.get("crawl")))).append("\n\n");
        b.append("Generated by `gatf plan` (").append(plan.get("format")).append(" v").append(plan.get("version")).append("). ")
         .append(counts.get("routes")).append(" route(s), ").append(counts.get("navigable")).append(" navigable, ")
         .append(counts.get("journeys")).append(" journey(s) (").append(counts.get("aiJourneys")).append(" from AI). Origin: ")
         .append(md(String.valueOf(src.get("origin")))).append(". AI: ").append(md(String.valueOf(ai.get("status")))).append(".\n\n");
        List<String> notes = (List<String>) plan.get("notes");
        if (!notes.isEmpty()) {
            b.append("## Notes\n\n");
            for (String n : notes) b.append("- ").append(md(n)).append('\n');
            b.append('\n');
        }
        Map<String, Map<String, Object>> byId = new LinkedHashMap<String, Map<String, Object>>();
        for (Map<String, Object> r : routes) byId.put(String.valueOf(r.get("id")), r);
        List<Map<String, Object>> sorted = new ArrayList<Map<String, Object>>(routes);
        Collections.sort(sorted, (x, y) -> Integer.compare(order(String.valueOf(x.get("priority"))), order(String.valueOf(y.get("priority")))));
        b.append("## Routes\n\n| Id | Priority | Route | Title | Journeys | Tested |\n|---|---|---|---|---|---|\n");
        for (Map<String, Object> r : sorted) {
            b.append("| ").append(r.get("id")).append(" | ").append(r.get("priority")).append("ai".equals(r.get("priorityFrom")) ? " (ai)" : "")
             .append(" | ").append(md(String.valueOf(r.get("route")))).append(" | ").append(md(String.valueOf(r.get("title"))))
             .append(" | ").append(((List<?>) r.get("journeys")).size())
             .append(" | ").append(r.get("tested") == null ? "?" : Boolean.TRUE.equals(r.get("tested")) ? "yes" : "**no**").append(" |\n");
        }
        b.append('\n');
        for (Map<String, Object> r : sorted) {
            b.append("## ").append(r.get("id")).append(" · ").append(md(String.valueOf(r.get("route")))).append("\n\n");
            if (!String.valueOf(r.get("title")).isEmpty()) b.append("Title: ").append(md(String.valueOf(r.get("title")))).append("  \n");
            b.append("Priority: ").append(r.get("priority")).append(" (").append(r.get("priorityFrom")).append(")");
            if (r.get("tested") != null) b.append(" · tested: ").append(Boolean.TRUE.equals(r.get("tested")) ? "yes" : "no");
            b.append("\n\n");
            for (String n : (List<String>) r.get("notes")) b.append("> ").append(md(n)).append("\n\n");
            Map<String, Map<String, Object>> els = new LinkedHashMap<String, Map<String, Object>>();
            for (Map<String, Object> e : (List<Map<String, Object>>) r.get("elements")) els.put(String.valueOf(e.get("ref")), e);
            for (Map<String, Object> j : (List<Map<String, Object>>) r.get("journeys")) {
                b.append("### ").append(md(String.valueOf(j.get("name")))).append(" (").append(j.get("goal")).append(", ").append(j.get("origin"))
                 .append(Boolean.TRUE.equals(j.get("sideEffects")) ? ", may change server state" : "").append(")\n\n");
                int k = 0;
                for (Map<String, Object> s : (List<Map<String, Object>>) j.get("steps")) b.append(++k).append(". ").append(step(s, byId)).append('\n');
                b.append('\n');
            }
        }
        Map<String, Object> un = (Map<String, Object>) plan.get("unplanned");
        if (((Number) un.get("count")).intValue() > 0) {
            b.append("## Not planned (cap)\n\n");
            for (Object u : (List<?>) un.get("routes")) b.append("- ").append(md(String.valueOf(u))).append('\n');
            int more = ((Number) un.get("count")).intValue() - ((List<?>) un.get("routes")).size();
            if (more > 0) b.append("- … and ").append(more).append(" more\n");
            b.append('\n');
        }
        return b.toString();
    }

    @SuppressWarnings("unchecked")
    private static String step(Map<String, Object> s, Map<String, Map<String, Object>> byId) {
        String intent = String.valueOf(s.get("intent"));
        Map<String, Object> route = s.get("route") == null ? null : byId.get(String.valueOf(s.get("route")));
        Map<String, Object> on = s.get("on") == null ? null : byId.get(String.valueOf(s.get("on")));
        Map<String, Object> el = null;
        if (on != null && s.get("ref") != null) {
            for (Map<String, Object> e : (List<Map<String, Object>>) on.get("elements")) if (s.get("ref").equals(e.get("ref"))) el = e;
        }
        String what = el == null ? "" : " " + elementName(el) + " (`" + code(String.valueOf(el.get("locator"))) + "`)";
        switch (intent) {
            case "navigate": return "navigate to " + s.get("route") + (route == null ? "" : " " + md(String.valueOf(route.get("route"))));
            case "assert-url": return "assert the URL is " + s.get("route") + (route == null ? "" : " " + md(String.valueOf(route.get("route"))));
            case "assert-title": return "assert the title" + (on == null ? "" : " is \u201c" + md(String.valueOf(on.get("title"))) + "\u201d");
            case "fill": return "fill" + what + " with " + s.get("data") + " data";
            case "select": return "select option " + s.get("option") + " of" + what;
            case "assert-text": return "assert the text of" + what + (el == null ? "" : " is \u201c" + md(String.valueOf(el.get("text"))) + "\u201d");
            default: return intent + what;
        }
    }

    private static String elementName(Map<String, Object> el) {
        String n = String.valueOf(el.get("label"));
        if (n.isEmpty()) n = String.valueOf(el.get("text"));
        if (n.isEmpty()) n = String.valueOf(el.get("name"));
        return el.get("ref") + (n.isEmpty() ? "" : " \u00ab" + md(n) + "\u00bb");
    }

    static int order(String p) {
        switch (p) {
            case "high": return 0;
            case "medium": return 1;
            case "low": return 2;
            case "error": return 3;
            default: return 4;
        }
    }

    /** Crawled text for Markdown: control characters out, Markdown punctuation and HTML escaped. */
    static String md(String v) {
        String s = CrawlMap.clean(v, 400);
        StringBuilder b = new StringBuilder(s.length() + 16);
        for (char c : s.toCharArray()) {
            switch (c) {
                case '&': b.append("&amp;"); break;
                case '<': b.append("&lt;"); break;
                case '>': b.append("&gt;"); break;
                case '\\': case '`': case '*': case '_': case '[': case ']': case '(': case ')': case '|': case '#': case '!': case '~':
                    b.append('\\').append(c); break;
                default: b.append(c);
            }
        }
        return b.toString();
    }

    /** A locator inside a code span: backticks cannot close it (they become a single quote), control characters out. */
    static String code(String v) {
        return CrawlMap.clean(v, 300).replace('`', '\'');
    }
}
